public class App {
    public static void main(String[] args) throws Exception {
        System.out.println("Operações relacionais");
        int num1, num2;
        num1 = 100;
        num2 = 10;

        // - comentário de 1 linha
        /*
         * comentário de muitas linhas
         */

        /*
         * > Maior que
         * < Menor que
         * >= Maior ou Igual
         * <= Menor ou igual=
         * == totalmente igual à
         * ! = é diferente de
         * 
         * OBS: A saida sempre retorna como verdadeiro ou falso // True or False
         * 
         */

        System.out.println(num1 > num2);
        System.out.println(num1 < num2);
        System.out.println(num1 >= num2);
        System.out.println(num1 <= num2);
        System.out.println(num1 == num2);
        System.out.println(num1 != num2);

        
    }
}